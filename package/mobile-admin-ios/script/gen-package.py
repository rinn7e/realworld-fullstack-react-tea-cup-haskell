#!/usr/bin/env python3
# Writes Package.swift (one module per file) and the dependencies of the app
# target in project.yml, from the files of src/ and their imports. Run it after
# adding, moving or removing a file, or changing the imports of one:
#
#   python3 script/gen-package.py
#
# The module of a file is its path under src/ with `_` between the folders
# (`Screen/UserScreen/Type.swift` is `Screen_UserScreen_Type`). The
# dependencies of a module are the modules of this app its file imports.
# `Root.swift` (`@main`) is in the app target, not in the package.
import glob
import os
import re

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

APP_TARGET_FILES = {"src/Root.swift"}
IMPORT = re.compile(r"^(?:@_spi\(\w+\) )?import (\w+)$", re.MULTILINE)


def module_of(path):
    return path[len("src/") : -len(".swift")].replace("/", "_")


files = sorted(glob.glob("src/**/*.swift", recursive=True))
file_of = {module_of(f): f for f in files}


def deps_of(path):
    imported = {m for m in IMPORT.findall(open(path).read()) if m in file_of}
    return sorted(imported, key=lambda m: file_of[m])


products, targets = [], []
for f in files:
    if f in APP_TARGET_FILES:
        continue
    m = module_of(f)
    d, name = os.path.split(f)
    others = sorted(e for e in os.listdir(d) if e != name and not e.startswith("."))
    args = [f'name: "{m}"']
    deps = deps_of(f)
    if deps:
        args.append("dependencies: [" + ", ".join(f'"{x}"' for x in deps) + "]")
    args.append(f'path: "{d}"')
    if others:
        args.append("exclude: [" + ", ".join(f'"{o}"' for o in others) + "]")
    args.append(f'sources: ["{name}"]')
    products.append(f'    .library(name: "{m}", targets: ["{m}"]),')
    targets.append("    .target(" + ", ".join(args) + "),")

package = """// swift-tools-version: 6.0
import PackageDescription

// One module per file (generated by script/gen-package.py): a module is the
// path of its file under `src/` with `_` between the folders, the Swift form of
// a Haskell module name (`Screen/UserScreen/Type.swift` is
// `Screen_UserScreen_Type`); the files of the root, `Handler/` and `Util/` have
// no prefix (`Update`, `Util_Guard`). The dependencies of a module are the
// modules its file imports, and SwiftPM refuses a cycle. The files of one
// folder share their internals through `@_spi(<folder module>)`, the
// `.Internal` pattern of Haskell (script/check-spi.sh). The app target
// (`project.yml`) holds `Root.swift` only, as the module `Root`.
let package = Package(
  name: "SentinelAdminModules",
  platforms: [.iOS(.v18), .macOS(.v15)],
  products: [
%s
  ],
  targets: [
%s
  ],
  swiftLanguageModes: [.v5]
)
""" % ("\n".join(products), "\n".join(targets))
open("Package.swift", "w").write(package)

# The products the app target links: the modules `Root.swift` imports
block = "".join(
    f"      - package: SentinelAdminModules\n        product: {m}\n"
    for m in deps_of("src/Root.swift")
)
yml = open("project.yml").read()
yml = re.sub(
    r"(    dependencies:\n)(?:      - package: .*\n        product: .*\n)+",
    lambda _: "    dependencies:\n" + block,
    yml,
)
open("project.yml", "w").write(yml)
